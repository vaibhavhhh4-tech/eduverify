'use client'

export type Row = Record<string, string | number | boolean | null | undefined>

function escapeCsv(value: unknown) {
  const s = value === null || value === undefined ? '' : String(value)
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s
}

export function toCsv(rows: Row[], columns?: string[]) {
  const cols = columns ?? (rows[0] ? Object.keys(rows[0]) : [])
  return [cols.join(','), ...rows.map((r) => cols.map((c) => escapeCsv(r[c])).join(','))].join('\n')
}

export function downloadBlob(content: BlobPart, filename: string, type: string) {
  const blob = new Blob([content], { type })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}

export function downloadCsv(rows: Row[], filename: string, columns?: string[]) {
  downloadBlob(toCsv(rows, columns), filename, 'text/csv;charset=utf-8')
}

export async function downloadPdf(opts: { title: string; subtitle?: string; rows: Row[]; columns: string[]; filename: string; summary?: [string, string][] }) {
  const { jsPDF } = await import('jspdf')
  const autoTable = (await import('jspdf-autotable')).default
  const doc = new jsPDF({ orientation: opts.columns.length > 6 ? 'landscape' : 'portrait' })
  const width = doc.internal.pageSize.getWidth()
  doc.setFillColor(19, 48, 107)
  doc.rect(0, 0, width, 22, 'F')
  doc.setTextColor(255, 255, 255)
  doc.setFontSize(14)
  doc.text('EduVerify', 14, 10)
  doc.setFontSize(8)
  doc.text('APAAR-Based National Student Identity & Verification System — Prototype', 14, 16)
  doc.setTextColor(20, 30, 50)
  doc.setFontSize(13)
  doc.text(opts.title, 14, 32)
  doc.setFontSize(9)
  doc.setTextColor(90, 100, 120)
  if (opts.subtitle) doc.text(opts.subtitle, 14, 38)
  let y = 44
  if (opts.summary?.length) {
    opts.summary.forEach(([k, v], i) => {
      doc.text(`${k}: ${v}`, 14 + (i % 3) * 62, y + Math.floor(i / 3) * 5)
    })
    y += Math.ceil(opts.summary.length / 3) * 5 + 3
  }
  autoTable(doc, {
    startY: y,
    head: [opts.columns],
    body: opts.rows.map((r) => opts.columns.map((c) => String(r[c] ?? ''))),
    styles: { fontSize: 8 },
    headStyles: { fillColor: [30, 86, 160] },
    alternateRowStyles: { fillColor: [244, 246, 250] },
  })
  const pages = doc.getNumberOfPages()
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i)
    doc.setFontSize(7)
    doc.setTextColor(120, 120, 120)
    doc.text(
      `Illustrative mock data generated by a prototype. Not an official AICTE / APAAR / DigiLocker document. Generated ${new Date().toLocaleString('en-IN')}. Page ${i} of ${pages}`,
      14,
      doc.internal.pageSize.getHeight() - 6,
    )
  }
  doc.save(opts.filename)
}
